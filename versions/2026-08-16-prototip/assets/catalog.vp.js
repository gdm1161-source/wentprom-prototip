/* Транслитерация марки в адрес: «ВР 80-75» → «vr-80-75» */
const CYR2LAT = {
  а:'a', б:'b', в:'v', г:'g', д:'d', е:'e', ё:'e', ж:'zh', з:'z', и:'i',
  й:'y', к:'k', л:'l', м:'m', н:'n', о:'o', п:'p', р:'r', с:'s', т:'t',
  у:'u', ф:'f', х:'kh', ц:'ts', ч:'ch', ш:'sh', щ:'shch', ъ:'', ы:'y',
  ь:'', э:'e', ю:'yu', я:'ya',
};
function slug(mk) {
  return String(mk).toLowerCase()
    .replace(/ø/g, 'd')
    .replace(/№/g, 'n')
    .replace(/[а-яё]/g, ch => CYR2LAT[ch] !== undefined ? CYR2LAT[ch] : ch)
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

