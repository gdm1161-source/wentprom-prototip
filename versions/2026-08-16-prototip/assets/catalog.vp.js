/** Позиция по идентификатору SKU */
function sku(id) {
  for (let i = 0; i < SKU.length; i++) if (SKU[i].id === id) return SKU[i];
  return null;
}

/** Серия по марке */
function seriesOf(mk) {
  for (let i = 0; i < SERIES.length; i++) if (SERIES[i].mk === mk) return SERIES[i];
  return null;
}

/* Достаём ключ из аргумента. Строку берём как есть — обращаться к id.sub у
   строки нельзя: String.prototype.sub существует как легаси-метод и всегда
   даёт истину, из-за чего поиск по строковому ключу молча ломается. */
function key1(id, props) {
  if (id === null || id === undefined) return null;
  if (typeof id !== 'object') return id;
  for (let i = 0; i < props.length; i++) if (id[props[i]]) return id[props[i]];
  return null;
}

/** Подраздел: по своему id, по марке серии или по объекту SKU */
function subOf(id) {
  const key = key1(id, ['sub']);
  if (key === null) return null;
  for (let i = 0; i < SUB.length; i++) if (SUB[i].id === key) return SUB[i];
  const s = seriesOf(key);
  if (s) { for (let i = 0; i < SUB.length; i++) if (SUB[i].id === s.sub) return SUB[i]; }
  return null;
}

/** Раздел: по своему id, по id подраздела, по марке серии или по объекту SKU */
function razdelOf(id) {
  const key = key1(id, ['razdel', 'sub', 'mk']);
  if (key === null) return null;
  for (let i = 0; i < RAZDEL.length; i++) if (RAZDEL[i].id === key) return RAZDEL[i];
  const sb = subOf(key);
  if (sb) { for (let i = 0; i < RAZDEL.length; i++) if (RAZDEL[i].id === sb.razdel) return RAZDEL[i]; }
  return null;
}

/** Адрес серии на новом сайте: /catalog/{раздел}/{подраздел}/{марка}/ */
function seriesUrl(mk) {
  const s = seriesOf(mk); if (!s) return '';
  const sb = subOf(s.sub); if (!sb) return '';
  const rz = razdelOf(sb.razdel); if (!rz) return '';
  return '/catalog/' + rz.slug + '/' + sb.slug + '/' + slug(mk) + '/';
}

/**
 * Поиск по каталогу. Терпим к латинице и разделителям:
 * «вр80-75» = «ВР 80-75» = «BP 80 75» = «вр 80 75».
 * Если по обозначению ничего не нашлось, а в запросе крупное число —
 * добираем ближайшие позиции по производительности.
 */
function search(query, limit) {
  const raw = String(query == null ? '' : query).trim();
  if (!raw) return [];
  const nq = norm(raw);
  if (!nq) return [];
  const lim = limit || 12;

  let hits = SKU.filter(r => norm(r.mk + ' ' + (r.size === null ? '' : r.size)).indexOf(nq) >= 0);

  /* Запрос мог быть названием раздела или подраздела */
  if (!hits.length) {
    const subs = SUB.filter(x => norm(x.name).indexOf(nq) >= 0 || norm(x.short).indexOf(nq) >= 0)
                    .map(x => x.id);
    if (subs.length) hits = SKU.filter(r => subs.indexOf(r.sub) >= 0);
  }
  if (!hits.length) {
    const rzs = RAZDEL.filter(x => norm(x.name).indexOf(nq) >= 0 || norm(x.short).indexOf(nq) >= 0)
                      .map(x => x.id);
    if (rzs.length) hits = SKU.filter(r => rzs.indexOf(r.razdel) >= 0);
  }

  /* Число в запросе — вероятно, искомый расход */
  const digits = raw.replace(/[^\d]/g, '');
  const asNum = digits ? Number(digits) : null;
  if (hits.length < 3 && asNum && asNum > 300) {
    const near = SKU.filter(r => r.q !== null)
      .map(r => ({r:r, d:Math.abs(r.q - asNum)}))
      .sort((a, b) => a.d - b.d).slice(0, 8).map(x => x.r);
    hits = hits.concat(near.filter(r => hits.indexOf(r) < 0));
  }
  return hits.slice(0, lim);
}

/**
 * Счётчики для фасетов: сколько серий и типоразмеров в каждом разделе и
 * подразделе. cnt рядом — счётчик товаров, который показывает боевой сайт;
 * расхождение с нашим sku ожидаемо и нужно как раз для сверки.
 */
function counts() {
  const byRazdel = {}, bySub = {};

  for (let i = 0; i < RAZDEL.length; i++) {
    const r = RAZDEL[i];
    byRazdel[r.id] = {name:r.name, series:0, sku:0, subs:r.subs.length, siteCnt:r.cnt, stub:!!r.stub};
  }
  for (let i = 0; i < SUB.length; i++) {
    const s = SUB[i];
    bySub[s.id] = {name:s.name, razdel:s.razdel, series:s.series.length, sku:0, stub:!!s.stub};
    if (byRazdel[s.razdel]) byRazdel[s.razdel].series += s.series.length;
  }
  for (let i = 0; i < SKU.length; i++) {
    const r = SKU[i];
    if (bySub[r.sub]) bySub[r.sub].sku++;
    if (byRazdel[r.razdel]) byRazdel[r.razdel].sku++;
  }
  return {razdel:byRazdel, sub:bySub,
          total:{razdel:RAZDEL.length, sub:SUB.length, series:SERIES.length, sku:SKU.length}};
}

