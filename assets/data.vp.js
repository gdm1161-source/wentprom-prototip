/* ── Поиск, терпимый к обозначениям ─────────────────────────────────── */
const LAT2CYR = {a:'а',b:'в',c:'с',e:'е',h:'н',k:'к',m:'м',o:'о',p:'р',t:'т',x:'х',y:'у'};
const norm = s => String(s).toLowerCase()
  .replace(/[a-z]/g, ch => LAT2CYR[ch] || ch)
  .replace(/[\s\-–—_/\\.,]+/g, '');

function search(query, limit) {
  const raw = String(query).trim();
  if (!raw) return [];
  const nq = norm(raw);
  const digits = raw.replace(/[^\d]/g, '');
  const asNum = digits ? Number(digits) : null;
  let hits = NUM.filter(r => norm(r.mk + ' ' + r.size).includes(nq));
  if (hits.length < 3 && asNum && asNum > 300) {
    const near = NUM.map(r => ({r, d:Math.abs(r.q - asNum)}))
      .sort((a, b) => a.d - b.d).slice(0, 8).map(x => x.r);
    hits = hits.concat(near.filter(r => !hits.includes(r)));
  }
  return hits.slice(0, limit || 9);
}

/* ── Подбор по рабочей точке ────────────────────────────────────────
   Внимание: методика подбора заводом НЕ передана. Здесь работает
   прямоугольная рабочая область серии с запасом — этого достаточно,
   чтобы проверить интерфейс, и НЕДОСТАТОЧНО, чтобы подбирать технику. */
function select(q, p, opts) {
  const o = opts || {};
  const res = [];
  for (const s of SERIES) {
    if (o.type && s.type !== o.type) continue;
    if (o.ind && !s.ind.includes(o.ind)) continue;
    if (q < s.qr[0] || q > s.qr[1]) continue;
    if (p < s.pr[0] || p > s.pr[1]) continue;
    /* Позиция обязана НАКРЫВАТЬ рабочую точку по обеим осям: отрицательный
       запас означает, что вентилятор в точку не попадает, и показывать его
       как подходящий нельзя. */
    const rows = NUM.filter(r => r.mk === s.mk && r.q >= q && r.p >= p);
    if (!rows.length) continue;
    rows.sort((a, b) => (a.q / q + a.p / p) - (b.q / q + b.p / p));
    const best = rows[0];
    const zq = Math.round((best.q / q - 1) * 100);
    const zp = Math.round((best.p / p - 1) * 100);
    /* Отсев по КАЖДОЙ оси отдельно, а не по обеим сразу: вентилятор с
       запасом 1039 % по расходу — это другой типоразмер, и то, что по
       давлению он лёг удачно, его не оправдывает. Прежнее условие через
       «и» пропускало такие строки в выдачу. */
    if (zq > 200 || zp > 200) continue;
    res.push({series:s, row:best, zapasQ:zq, zapasP:zp});
  }
  res.sort((a, b) => (a.zapasQ + a.zapasP) - (b.zapasQ + b.zapasP));
  return res;
}

