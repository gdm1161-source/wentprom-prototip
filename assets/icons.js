const ALIAS = { 'fire':'valve' };   // раздел противопожарной вентиляции — это клапан

/** Силуэт по ключу. `title` делает его доступным для скринридера. */
export function icon(key, { size = 64, cls = '', title = '' } = {}){
  const body = SH[key] || SH[ALIAS[key]] || SH.fan;
  const h = Math.round(size * 44 / 64);
  return `<svg class="silh ${cls}" width="${size}" height="${h}" viewBox="0 0 64 44"
    fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round"
    stroke-linejoin="round" vector-effect="non-scaling-stroke"
    ${title ? 'role="img"' : 'aria-hidden="true" focusable="false"'}>
    ${title ? `<title>${title}</title>` : ''}${body}</svg>`;
}

/** Силуэт по серии — тот же выбор, что делает каталог. */
export function iconForSeries(s){
  const k = s.kind || '';
  if(/Осевой|Шахтный|Подпор/.test(k))  return 'axial';
  if(/Крышный/.test(k))                return 'roof';
  if(/Канальный/.test(k))              return s.id === 'vkk' ? 'duct-round' : 'duct-rect';
  if(/Пылевой|Высокого давления/.test(k)) return 'dust';
  if(/Индустриальный/.test(k))         return 'heavy';
  if(/Дымосос|Дутьевой/.test(k))       return 'boiler';
  if(/Дымоудаления/.test(k))           return 'fire';
  return 'radial';
}

