/* Ряд NUMS хранит РАЗНОЕ: у радиальных и осевых это номер агрегата (№ 6,3),
   у ВКК — диаметр в мм (Ø 250), у ВКПН — код сечения (4020 = 400×200 мм).
   Всё, что зависит от размера (масса, диаметр), обязано считаться от
   аэродинамического номера, а не от этого кода — иначе ВКПН «весит» тонны. */
function aeroOf(seriesId, num){
  if(seriesId === 'vkk')                       // Ø в мм → № = Ø/100
    return { aero: num / 100, dia: num, label: `Ø ${num}` };

  if(seriesId === 'vkpn'){                     // 4020 → 400×200 мм
    const a = Math.floor(num / 100) * 10, b = (num % 100) * 10;
    const de = 2 * a * b / (a + b);            // эквивалентный диаметр
    return { aero: de / 100, dia: Math.round(de), label: `${a}×${b}` };
  }
  return { aero: num, dia: num * 100, label: `№ ${String(num).replace('.', ',')}` };
}

function pickRpm(range, k){
  const inRange = RPM_ROW.filter(r => r >= range[0] && r <= range[1]);
  const row = inRange.length ? inRange : [range[1]];
  return row[Math.min(row.length - 1, Math.round(k * (row.length - 1)))];
}
function motorFor(kw){ return MOTORS.find(m => m >= kw * 1.15) || MOTORS[MOTORS.length - 1]; }

/** Демонстрационные типоразмеры серии. */
export function sizesOf(s){
  const nums = NUMS[s.id] || [s.nSizes];
  const last = nums.length - 1 || 1;

  /* У вентиляторов дымоудаления завод публикует не диапазон, а только верх
     («до 92 000 м³/ч»), а у ВРз ДУ давление не опубликовано вовсе. Нулевую
     границу нельзя выводить как рабочую цифру: Q = 0 — это не типоразмер.
     Подставляем правдоподобный низ и помечаем строку assumed — она и так
     демонстрационная, но пусть будет видно, что нижняя граница домыслена. */
  const assumed = s.q[0] <= 0 || s.p[1] <= 0;
  const qLo = s.q[0] > 0 ? s.q[0] : Math.round(s.q[1] * 0.08);
  const pHi = s.p[1] > 0 ? s.p[1] : 2870;      // порядок соседней серии ВРм ДУ
  const pLo = s.p[0] > 0 ? s.p[0] : Math.round(pHi * 0.15);

  return nums.map((num, i) => {
    const t = last ? i / last : 0;            // положение в ряду 0…1
    const q = Math.round(qLo + (s.q[1] - qLo) * Math.pow(t, 1.7));
    const p = Math.round(pLo + (pHi - pLo) * Math.pow(t, 0.75));
    const rpm = pickRpm(s.rpm, 1 - t * 0.75);
    const eta = 0.62 + 0.22 * Math.sin(Math.PI * (0.25 + 0.6 * t));  // 0,62…0,84
    const shaft = (q / 3600) * p / (eta * 1000);                     // кВт на валу
    const kw = motorFor(Math.max(s.kw[0], Math.min(s.kw[1], shaft)));
    const { aero, dia, label } = aeroOf(s.id, num);
    const mass = Math.round(28 * Math.pow(aero / 2.5, 2.3));
    const lpa = Math.round(62 + 16 * t + (p > 3000 ? 6 : 0));
    return {
      id: `${s.id}-${String(num).replace('.', '-')}`,
      num, label,
      q, p, rpm, kw, eta: +eta.toFixed(2), mass, lpa, dia,
      stock: (i * 7 + s.mark.length) % 5 === 0 ? 'склад' : ((i * 3) % 4 === 0 ? '10 дн.' : '20 дн.'),
      demo: true, assumed
    };
  });
}

/** Все демонстрационные типоразмеры группы одной таблицей. */
export function sizesOfGroup(groupSlug){
  const out = [];
  SERIES.filter(s => s.group === groupSlug).forEach(s => {
    sizesOf(s).forEach(z => out.push({ ...z, series: s.mark, seriesId: s.id, sub: s.sub,
                                       kind: s.kind, blade: s.blade || '—', exec: s.exec }));
  });
  return out;
}

